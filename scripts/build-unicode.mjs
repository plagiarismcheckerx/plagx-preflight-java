// Generates src/main/java/.../UnicodeData.java from the JavaScript engine so the
// Java port matches the JavaScript reference exactly (Java's own Unicode tables are older):
//  - \p{L}, \p{M}, \p{Lu}, \p{Ll} as Java regex character-class content;
//  - toUpperCase / toLowerCase mappings that differ from "unchanged".
// The output is plain ASCII. Usage: node scripts/build-unicode.mjs
import { writeFileSync } from 'node:fs';

const BS = "\\\\"; // two backslashes: a regex escape inside a Java string
const esc = (n) => (n > 0xffff ? `${BS}x{${n.toString(16).toUpperCase()}}` : `${BS}u${n.toString(16).toUpperCase().padStart(4, "0")}`);
const hex = (n) => n.toString(16).toUpperCase();

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp += 1) {
    const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

const cls = (re) => ranges(re).map(([a, b]) => (a === b ? esc(a) : `${esc(a)}-${esc(b)}`));

function caseMap(fn) {
  const out = [];
  for (let cp = 0; cp < 0x110000; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    const m = fn(s);
    if (m !== s) out.push(`${hex(cp)}=${[...m].map((c) => hex(c.codePointAt(0))).join(' ')}`);
  }
  return out;
}

function lines(parts, sep) {
  const out = [];
  let line = '';
  for (const p of parts) {
    if (line && line.length + p.length > 110) { out.push(line); line = ''; }
    line += (line ? sep : '') + p;
  }
  if (line) out.push(line);
  return out.map((l, i) => `        "${i > 0 && sep ? sep : ''}${l}"`).join(' +\n');
}

let java = `// Generated by scripts/build-unicode.mjs from the JavaScript engine (Node ${process.versions.node},
// Unicode ${process.versions.unicode}) so results match the JavaScript reference. Do not edit.
package com.plagiarismcheckerx.plagx.preflight;

final class UnicodeData {
    private UnicodeData() {}
`;
for (const [name, re] of Object.entries({ L: /\p{L}/u, M: /\p{M}/u, Lu: /\p{Lu}/u, Ll: /\p{Ll}/u })) {
  java += `\n    /** Character-class content for \\p{${name}}. */\n    static final String ${name.toUpperCase()} =\n${lines(cls(re), '')};\n`;
}
java += `\n    /** String.prototype.toUpperCase for every code point it changes: "cp=mapped mapped,...". */\n    static final String UPPER =\n${lines(caseMap((s) => s.toUpperCase()), ',')};\n`;
java += `\n    /** String.prototype.toLowerCase for every code point it changes (context-free). */\n    static final String LOWER =\n${lines(caseMap((s) => s.toLowerCase()), ',')};\n}\n`;
writeFileSync(new URL('../src/main/java/com/plagiarismcheckerx/plagx/preflight/UnicodeData.java', import.meta.url), java);
console.log('Wrote UnicodeData.java');
